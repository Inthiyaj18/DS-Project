#!/usr/bin/env python3
"""Bundle the genuine seaborn example datasets for the MBU Code Lab.

The Code Lab runs Python in Pyodide (WebAssembly), which has no `ssl`
module, so `urllib.request` cannot fetch `https://` URLs.  To make
`sns.load_dataset(name)` work with no external network at execution time
we ship real copies of the datasets:

  assets/datasets/<name>.csv   genuine CSV for every dataset (served on demand)
  js/datasets.js               the common datasets embedded so the worker /
                               main-thread fallback can load them with zero
                               network (and the full official name list)

Source of every file: https://github.com/mwaskom/seaborn-data
License: BSD-3-Clause (see the notice in launch_notes / README).

Re-run this script to refresh the bundles.  It is a build helper only;
nothing at runtime depends on it.
"""
import json
import os
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASSET_DIR = os.path.join(ROOT, "assets", "datasets")
JS_PATH = os.path.join(ROOT, "js", "datasets.js")
BASE = "https://raw.githubusercontent.com/mwaskom/seaborn-data/master"

# Datasets embedded into js/datasets.js (small enough to ship in the bundle
# and enough to cover the common educational examples completely offline).
EMBED = [
    "anagrams", "anscombe", "attention", "car_crashes", "dots", "dowjones",
    "exercise", "flights", "fmri", "geyser", "glue", "healthexp", "iris",
    "mpg", "penguins", "planets", "tips", "titanic",
]

HEADER = """\
/* =====================================================================
   datasets.js  -  Genuine seaborn example datasets bundled for the
   MBU Data Science Lab Code Lab.

   The Python sandbox (Pyodide / WebAssembly) has no `ssl` module, so
   urllib cannot fetch https URLs.  js/pycode.js patches urllib to use
   Pyodide's secure browser fetch, and uses these embedded copies first
   so sns.load_dataset() works with no network at all for common names.

   Source : https://github.com/mwaskom/seaborn-data  (BSD-3-Clause)
   Data   : unmodified copies - no fabricated or altered values.

   Generated by tools/build_datasets.py - do not edit by hand.
   ===================================================================== */
"""


def fetch(url):
    with urllib.request.urlopen(url, timeout=60) as response:
        return response.read()


def main():
    os.makedirs(ASSET_DIR, exist_ok=True)

    names_text = fetch(BASE + "/dataset_names.txt").decode("utf-8")
    names = [line.strip() for line in names_text.splitlines() if line.strip()]

    embedded = {}
    for name in names:
        destination = os.path.join(ASSET_DIR, name + ".csv")
        if os.path.exists(destination) and os.path.getsize(destination) > 0:
            raw = open(destination, "rb").read()
        else:
            raw = fetch("%s/%s.csv" % (BASE, name))
            with open(destination, "wb") as handle:
                handle.write(raw)
        if name in EMBED:
            embedded[name] = raw.decode("utf-8")
        print("%-14s %8d bytes" % (name, len(raw)))

    out = [HEADER.rstrip("\n")]
    out.append("self.MBU_DATASET_NAMES = " + json.dumps(names_text) + ";")
    out.append("self.MBU_EMBEDDED_DATASETS = {")
    for name in EMBED:
        if name in embedded:
            out.append("  " + json.dumps(name) + ": " + json.dumps(embedded[name]) + ",")
    out.append("};")
    out.append("")

    with open(JS_PATH, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(out))

    print("\nwrote %d datasets to %s" % (len(names), ASSET_DIR))
    print("wrote %s (embedded: %s)" % (JS_PATH, ", ".join(sorted(embedded))))


if __name__ == "__main__":
    main()
